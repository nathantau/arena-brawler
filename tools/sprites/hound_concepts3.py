def tone(rows: list[str], leg_row: int, ridge: list[tuple[int, int]]) -> list[str]:
    """Authoring helper: highlights picked out on the lit ridge, a darker belly, and the legs split into near (mid tone) and far
    (darkest) by their order across the row."""
    g = [list(r.ljust(44, ".")) for r in rows]
    for y, x in ridge:
        if g[y][x] in "VD":
            g[y][x] = "L"
    for y in range(len(g)):
        if y >= leg_row:
            seg = 0
            x = 0
            while x < len(g[y]):
                if g[y][x] == "O" and x + 1 < len(g[y]) and g[y][x + 1] == "D":
                    k = x + 1
                    while k < len(g[y]) and g[y][k] == "D":
                        g[y][k] = "V" if seg % 2 else "O"
                        k += 1
                    seg += 1
                    x = k
                else:
                    x += 1
        elif leg_row - 4 <= y < leg_row:  # belly and chest underside: the darkest tone, dithered into the base
            for x in range(len(g[y])):
                if g[y][x] == "D" and (y == leg_row - 1 or (x + y) % 2 == 0 and y >= leg_row - 2):
                    g[y][x] = "O"
    return ["".join(r).rstrip(".") for r in g]


def grid_image(rows: list[str]) -> Image.Image:
    w = max(len(r) for r in rows)
    img = Image.new("RGBA", (w, len(rows)), (0, 0, 0, 0))
    px = img.load()
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in COL:
                px[x, y] = COL[ch] + (255,)
    return img


def place(cell: Image.Image, n: int = 40, ground: int = 33, centre: int = 20) -> Image.Image:
    """Puts a grid sprite on a small transparent canvas, paws on row `ground`."""
    out = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    out.alpha_composite(cell, (centre - cell.width // 2, ground - cell.height + 1))
    return out


def main() -> None:
    out_path = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("hound_concepts3.png")
    for name, rows in (("side1", SIDE1), ("side2", SIDE2), ("tq", TQ)):
        for i, r in enumerate(rows):
            if len(r) != len(rows[0]):
                print(f"{name} row {i}: width {len(r)} != {len(rows[0])}")
    shadow = Image.open(Path(__file__).resolve().parents[2] / "assets/sprites/shadow.png").convert("RGBA").crop((0, 0, 96, 96))
    # 96 px cells (like the sheets): the hound is drawn at game scale (1 art px) and Shadow beside it at the same scale
    cells = [("Shadow", shadow), ("hound side 1", None), ("hound side 2", None), ("hound 3/4", None)]
    box = (4, 14, 92, 78)
    w, h = box[2] - box[0], box[3] - box[1]
    bg = (58, 64, 74)
    S8 = 8
    img = Image.new("RGB", (len(cells) * w * S8, h * S8 + 200), bg)
    d = ImageDraw.Draw(img)
    half = S8
    for i, (label, im) in enumerate(cells):
        layer = Image.new("RGBA", (96, 96), bg + (255,))
        sh = Image.new("RGBA", (96, 96), (0, 0, 0, 0))
        ground = 70
        sd = ImageDraw.Draw(sh)
        rx = 14 if im is not None else 13
        sd.ellipse((48 - rx, ground - 3, 48 + rx, ground + 5), fill=(0, 0, 0, 77))  # the fighters' soft 0.3 ellipse
        layer.alpha_composite(sh)
        if im is None:
            ridge1 = [(7, x) for x in range(9, 20, 3)] + [(8, x) for x in range(8, 24, 4)] + [(5, 30), (6, 28), (4, 27), (3, 28), (3, 31)]
            grid = {"hound side 1": tone(SIDE1, 17, ridge1), "hound side 2": tone(SIDE2, 17, ridge1), "hound 3/4": tone(TQ, 16, [(8, x) for x in range(8, 15, 3)] + [(9, x) for x in range(6, 18, 4)] + [(3, 17), (3, 20)])}[label]
            g = grid_image(grid)
            layer.alpha_composite(g, (48 - g.width // 2, ground + 1 - g.height))
        else:
            layer.alpha_composite(im)
        cell = layer.convert("RGB").crop(box)
        x0 = i * w * half
        img.paste(cell.resize((w * half, h * half), Image.NEAREST), (x0, 0))
        d.text((x0 + 4, h * half + 2), label, fill=(255, 230, 120))
        img.paste(cell, (x0 + 4, h * half + 20))  # 1x
        img.paste(cell.resize((w * 2, h * 2), Image.NEAREST), (x0 + 4 + w + 8, h * half + 20))  # 2x
    img.save(out_path)
    print("wrote", out_path, img.size)


if __name__ == "__main__":
    main()
